def wire_related():
    by_cat = {}
    for p in PAGES:
        by_cat.setdefault(p["category"], []).append(p["slug"])
    all_slugs = [p["slug"] for p in PAGES]
    for i, p in enumerate(PAGES):
        related = []
        for s in by_cat.get(p["category"], []):
            if s != p["slug"]:
                related.append(s)
        # add cross-links
        extras = ["ritualnye-uslugi-almaty", "granitnye-pamyatniki", "katafalk-almaty", "kontakty", "faq"]
        for e in extras:
            if e != p["slug"] and e not in related:
                related.append(e)
        # rotate uniqueness
        related = related[:4] + [all_slugs[(i + 7) % len(all_slugs)], all_slugs[(i + 13) % len(all_slugs)]]
        seen = set()
        out = []
        for s in related:
            if s != p["slug"] and s not in seen:
                seen.add(s)
                out.append(s)
            if len(out) >= 6:
                break
        p["related_slugs"] = out


wire_related()

